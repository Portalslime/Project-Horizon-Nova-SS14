using System;
using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared._Arcane.ErpPanel;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Localization;
using Robust.Shared.Prototypes;
using Robust.Shared.Utility;

namespace Content.Client._Arcane.ErpPanel;

/// <summary>
/// HN: окно создания/редактирования собственной эмоции.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class CustomEmoteWindow : FancyWindow
{
    [Dependency] private readonly IPrototypeManager _prototypeManager = default!;

    private readonly ErpPanelCustomInteraction? _existing;
    private readonly Action<ErpPanelCustomInteraction> _onSave;
    private readonly Action<int> _onDelete;
    private readonly Dictionary<int, string> _categoryIds = new();

    public CustomEmoteWindow(
        ErpPanelCustomInteraction? existing,
        Action<ErpPanelCustomInteraction> onSave,
        Action<int> onDelete)
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _existing = existing;
        _onSave = onSave;
        _onDelete = onDelete;

        Title = Loc.GetString(existing == null
            ? "erp-panel-custom-create-title"
            : "erp-panel-custom-edit-title");

        DeleteButton.Visible = existing != null && existing.Id != 0;

        NameInput.Text = existing?.Name ?? string.Empty;
        MessageInput.TextRope = new Rope.Leaf(existing?.Message ?? string.Empty);
        SelfMessageInput.TextRope = new Rope.Leaf(existing?.SelfMessage ?? string.Empty);
        CooldownSlider.SetValueWithoutEvent(existing?.Cooldown ?? 3f);
        UpdateCooldownLabel(CooldownSlider.Value);

        LoadCategories(existing?.Category);

        CooldownSlider.OnValueChanged += _ => UpdateCooldownLabel(CooldownSlider.Value);
        SaveButton.OnPressed += _ => Save();
        CancelButton.OnPressed += _ => Close();
        DeleteButton.OnPressed += _ => Delete();
    }

    private void LoadCategories(string? selected)
    {
        CategoryOption.Clear();
        _categoryIds.Clear();

        var id = 0;
        _categoryIds[id] = ErpPanelCustomInteraction.CustomCategoryId;
        CategoryOption.AddItem(Loc.GetString("erp-panel-category-custom-name"), id);
        if (selected == ErpPanelCustomInteraction.CustomCategoryId)
            CategoryOption.SelectId(id);

        foreach (var category in _prototypeManager.EnumeratePrototypes<PanelInteractionCategoryPrototype>()
                     .OrderBy(category => Loc.GetString($"erp-panel-category-{ToKebabCase(category.ID)}-name")))
        {
            id++;
            _categoryIds[id] = category.ID;
            CategoryOption.AddItem(Loc.GetString($"erp-panel-category-{ToKebabCase(category.ID)}-name"), id);

            if (category.ID == selected)
                CategoryOption.SelectId(id);
        }

        if (CategoryOption.SelectedId < 0)
            CategoryOption.SelectId(0);
    }

    private void UpdateCooldownLabel(float value)
    {
        CooldownLabel.Text = Loc.GetString("erp-panel-custom-cooldown-value",
            ("seconds", (int) Math.Round(value)));
    }

    private void Save()
    {
        var name = NameInput.Text.Trim();
        var message = Rope.Collapse(MessageInput.TextRope).Trim();
        var selfMessage = Rope.Collapse(SelfMessageInput.TextRope).Trim();

        if (string.IsNullOrWhiteSpace(name) || string.IsNullOrWhiteSpace(message))
        {
            ValidationLabel.Text = Loc.GetString("erp-panel-custom-validation-required");
            return;
        }

        if (name.Length > 48)
            name = name[..48];

        if (message.Length > 300)
            message = message[..300];

        if (selfMessage.Length > 300)
            selfMessage = selfMessage[..300];

        var category = ErpPanelCustomInteraction.CustomCategoryId;
        if (_categoryIds.TryGetValue(CategoryOption.SelectedId, out var categoryId))
            category = categoryId;

        var result = new ErpPanelCustomInteraction(
            _existing?.Id ?? 0,
            name,
            category,
            message,
            selfMessage,
            Math.Clamp(CooldownSlider.Value, 1f, 60f));

        _onSave(result);
        Close();
    }

    private void Delete()
    {
        if (_existing == null || _existing.Id == 0)
            return;

        _onDelete(_existing.Id);
        Close();
    }

    private static string ToKebabCase(string value)
    {
        var builder = new System.Text.StringBuilder(value.Length * 2);

        for (var i = 0; i < value.Length; i++)
        {
            var character = value[i];

            if (char.IsUpper(character))
            {
                if (i > 0)
                    builder.Append('-');

                builder.Append(char.ToLowerInvariant(character));
                continue;
            }

            builder.Append(character);
        }

        return builder.ToString();
    }
}
